function baseRecipe(
  data: Omit<
    Recipe,
    | 'id'
    | 'lines'
    | 'steps'
    | 'bake'
    | 'prepMinutes'
    | 'laborMinutes'
    | 'extraCostPerBatch'
    | 'mermaPct'
    | 'priceMode'
    | 'itbms'
    | 'favorite'
    | 'createdAt'
    | 'updatedAt'
  > & {
    id: string
    lines: RecipeLine[]
    steps: RecipeStep[]
    bake: Recipe['bake']
    prepMinutes: number
    laborMinutes: number
    extraCostPerBatch: number
    mermaPct: number
  },
): Recipe {
  return {
    ...data,
    favorite: false,
    priceMode: 'auto',
    itbms: true,
    createdAt: NOW,
    updatedAt: NOW,
  }
}

function pack(
  id: string,
  name: string,
  packPrice: number,
  coversUnits: number,
): PackagingItem {
  return { id, name, packPrice, coversUnits }
}


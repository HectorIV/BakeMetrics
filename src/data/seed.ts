const NOW = new Date().toISOString()

type IngredientSeed = Pick<
  Ingredient,
  'id' | 'name' | 'category' | 'baseUnit' | 'packPrice' | 'packQty' | 'packUnit'
> &
  Partial<Ingredient>

function ing(seed: IngredientSeed): Ingredient {
  return {
    stock: 0,
    minStock: 0,
    customUnits: [],
    wastePct: 0,
    priceEstimated: true,
    ...seed,
    id: seed.id,
    name: seed.name,
    category: seed.category,
    baseUnit: seed.baseUnit,
    packPrice: seed.packPrice,
    packQty: seed.packQty,
    packUnit: seed.packUnit,
  }
}

function line(
  id: string,
  ingredientId: string,
  qty: number,
  unit: string,
  note?: string,
): RecipeLine {
  return { id, ingredientId, qty, unit, ...(note ? { note } : {}) }
}

function step(id: string, text: string, minutes?: number): RecipeStep {
  return { id, text, ...(minutes ? { minutes } : {}) }
}

